fn launch_config(numel: usize) -> Result<LaunchConfig> {
    let numel = u32::try_from(numel).map_err(|_| Error::ShapeElementCountOverflow)?;
    Ok(LaunchConfig::for_num_elems(numel))
}

fn launch_config_blocks(num_blocks: usize) -> Result<LaunchConfig> {
    let num_blocks = u32::try_from(num_blocks).map_err(|_| Error::ShapeElementCountOverflow)?;
    Ok(LaunchConfig {
        grid_dim: (num_blocks, 1, 1),
        block_dim: (1024, 1, 1),
        shared_mem_bytes: 0,
    })
}

/// Fuses U8 NHWC batch conversion, channel normalization, and NHWC -> NCHW
/// materialization into one device kernel. The per-channel affine arrays are
/// tiny host-to-device parameters; image pixels are transferred separately as
/// U8 and never staged through a CPU F32 tensor.
pub(crate) fn normalize_u8_nhwc_to_nchw_f32(
    device: &CudaDevice,
    src: &CudaStorageView<'_>,
    dst: &mut CudaStorageSlice,
    dims: [usize; 4],
    scale: &[f32],
    bias: &[f32],
) -> Result<()> {
    let [batch, height, width, channels] = dims;
    let numel = batch
        .checked_mul(height)
        .and_then(|size| size.checked_mul(width))
        .and_then(|size| size.checked_mul(channels))
        .ok_or(Error::ShapeElementCountOverflow)?;
    if numel == 0 {
        return Ok(());
    }
    if scale.len() != channels || bias.len() != channels {
        return Err(Error::ShapeMismatch {
            expected: channels,
            actual: scale.len().min(bias.len()),
        });
    }
    let src = match src {
        CudaStorageView::U8(src) => src,
        _ => {
            return Err(Error::UnsupportedCudaOp {
                op: "normalize input dtype",
            });
        }
    };
    let dst = match dst {
        CudaStorageSlice::F32(dst) => dst,
        _ => {
            return Err(Error::UnsupportedCudaOp {
                op: "normalize output dtype",
            });
        }
    };

    let device_handle = std::sync::Arc::new(device.clone());
    let scale = super::storage::CudaStorage::from_host_slice(device_handle.clone(), scale)?;
    let bias = super::storage::CudaStorage::from_host_slice(device_handle, bias)?;
    let rgb_fast_path = channels == 3;
    let function_name = if rgb_fast_path {
        "normalize_nhwc3_u8_to_nchw_f32"
    } else {
        "normalize_nhwc_u8_to_nchw_f32"
    };
    let function = device.get_or_load_func(rivet_kernels::VISION_NORMALIZE, function_name)?;
    let stream = device.cuda_stream();
    let launch_numel = if rgb_fast_path {
        numel / channels
    } else {
        numel
    };
    let launch = if rgb_fast_path {
        unsafe {
            stream
                .launch_builder(&function)
                .arg(src)
                .arg(dst)
                .arg(&batch)
                .arg(&height)
                .arg(&width)
                .arg(&scale)
                .arg(&bias)
                .launch(launch_config(launch_numel)?)
        }
    } else {
        unsafe {
            stream
                .launch_builder(&function)
                .arg(src)
                .arg(dst)
                .arg(&batch)
                .arg(&height)
                .arg(&width)
                .arg(&channels)
                .arg(&scale)
                .arg(&bias)
                .launch(launch_config(launch_numel)?)
        }
    };
    launch.map_err(|error| cuda_error("kernel_launch", function_name, error))?;
    device.record_kernel_launch();
    Ok(())
}

/// Batch-native crop/resize/flip + normalize + HWC->CHW RGB kernel. Random
/// parameters are generated by the vision semantic RNG and uploaded once per
/// batch, so this backend kernel has no dependence on worker scheduling.
pub(crate) fn vision_augment_normalize_u8_nhwc_to_nchw_f32(
    device: &CudaDevice,
    src: &CudaStorageView<'_>,
    dst: &mut CudaStorageSlice,
    input_dims: [usize; 4],
    output_dims: [usize; 4],
    crop_params: &[u32],
    filter: i32,
    scale: &[f32],
    bias: &[f32],
) -> Result<()> {
    let [batch, input_height, input_width, channels] = input_dims;
    let [output_batch, output_channels, output_height, output_width] = output_dims;
    if batch != output_batch || channels != 3 || output_channels != 3 {
        return Err(Error::UnsupportedCudaOp {
            op: "vision augmentation currently requires matching RGB batches",
        });
    }
    if crop_params.len() != batch.saturating_mul(8) {
        return Err(Error::ShapeMismatch {
            expected: batch.saturating_mul(8),
            actual: crop_params.len(),
        });
    }
    if scale.len() != 3 || bias.len() != 3 {
        return Err(Error::ShapeMismatch {
            expected: 3,
            actual: scale.len().min(bias.len()),
        });
    }
    let output_len = batch
        .checked_mul(3)
        .and_then(|size| size.checked_mul(output_height))
        .and_then(|size| size.checked_mul(output_width))
        .ok_or(Error::ShapeElementCountOverflow)?;
    if output_len == 0 {
        return Ok(());
    }
    let output_pixels = batch
        .checked_mul(output_height)
        .and_then(|size| size.checked_mul(output_width))
        .ok_or(Error::ShapeElementCountOverflow)?;
    let src = match src {
        CudaStorageView::U8(src) => src,
        _ => {
            return Err(Error::UnsupportedCudaOp {
                op: "vision augmentation input dtype",
            });
        }
    };
    let dst = match dst {
        CudaStorageSlice::F32(dst) => dst,
        _ => {
            return Err(Error::UnsupportedCudaOp {
                op: "vision augmentation output dtype",
            });
        }
    };
    let device_handle = std::sync::Arc::new(device.clone());
    let crop_params = super::storage::CudaStorage::from_host_slice(
        std::sync::Arc::clone(&device_handle),
        crop_params,
    )?;
    let scale =
        super::storage::CudaStorage::from_host_slice(std::sync::Arc::clone(&device_handle), scale)?;
    let bias = super::storage::CudaStorage::from_host_slice(device_handle, bias)?;
    let function_name = match filter {
        0 => "vision_augment_normalize_nhwc3_u8_to_nchw_f32_nearest",
        1 => "vision_augment_normalize_nhwc3_u8_to_nchw_f32_bilinear",
        2 => "vision_augment_normalize_nhwc3_u8_to_nchw_f32_bicubic",
        3 => "vision_augment_normalize_nhwc3_u8_to_nchw_f32_lanczos3",
        _ => {
            return Err(Error::UnsupportedCudaOp {
                op: "vision augmentation interpolation mode",
            });
        }
    };
    let function = device.get_or_load_func(rivet_kernels::VISION_NORMALIZE, function_name)?;
    let stream = device.cuda_stream();
    unsafe {
        stream
            .launch_builder(&function)
            .arg(src)
            .arg(dst)
            .arg(&batch)
            .arg(&input_height)
            .arg(&input_width)
            .arg(&output_height)
            .arg(&output_width)
            .arg(&crop_params)
            .arg(&scale)
            .arg(&bias)
            .launch(launch_config(output_pixels)?)
    }
    .map_err(|error| cuda_error("kernel_launch", function_name, error))?;
    device.record_kernel_launch();
    Ok(())
}

fn cuda_error(
    op: &'static str,
    name: impl std::fmt::Display,
    error: impl std::fmt::Display,
) -> Error {
    Error::CudaOperationFailed {
        op,
        message: format!("{name}: {error}"),
    }
}

fn layout_info(device: &CudaDevice, layout: &Layout) -> Result<LayoutInfo> {
    let mut values = Vec::with_capacity(layout.dims().len() * 2);
    values.extend_from_slice(layout.dims());
    values.extend_from_slice(layout.stride());
    if !values.is_empty() {
        device.record_h2d();
    }
    let values = device
        .cuda_stream()
        .clone_htod(&values)
        .map_err(|error| cuda_error("kernel_layout_info", "layout", error))?;
    Ok(LayoutInfo {
        values,
        rank: layout.dims().len(),
    })
}

fn layout_view<'a>(data: &'a CudaStorageSlice, layout: &Layout) -> Result<CudaStorageView<'a>> {
    let start = layout.start_offset();
    let len = data
        .len()
        .checked_sub(start)
        .ok_or(Error::StorageOutOfBounds)?;
    data.view(start, len)
}

fn launch_fill<T: DeviceRepr>(
    device: &CudaDevice,
    function_name: &str,
    dst: &mut CudaSlice<T>,
    value: T,
    numel: usize,
) -> Result<()> {
    if numel == 0 {
        return Ok(());
    }
    let function = device.get_or_load_func(rivet_kernels::FILL, function_name)?;
    let stream = device.cuda_stream();
    let config = launch_config(numel)?;
    unsafe {
        stream
            .launch_builder(&function)
            .arg(dst)
            .arg(&value)
            .arg(&numel)
            .launch(config)
    }
    .map_err(|error| cuda_error("kernel_launch", function_name, error))?;
    device.record_kernel_launch();
    Ok(())
}

fn launch_copy_layout<T: DeviceRepr>(
    device: &CudaDevice,
    function_name: &str,
    src: &CudaView<'_, T>,
    dst: &mut CudaSlice<T>,
    layout: &Layout,
    numel: usize,
) -> Result<()> {
    if numel == 0 {
        return Ok(());
    }
    let info = layout_info(device, layout)?;
    let function = device.get_or_load_func(rivet_kernels::COPY, function_name)?;
    let stream = device.cuda_stream();
    let config = launch_config(numel)?;
    unsafe {
        stream
            .launch_builder(&function)
            .arg(&numel)
            .arg(&info.rank)
            .arg(&info.values)
            .arg(src)
            .arg(dst)
            .launch(config)
    }
    .map_err(|error| cuda_error("kernel_launch", function_name, error))?;
    device.record_kernel_launch();
    Ok(())
}

