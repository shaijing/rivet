fn index_layout_sizes(layout: &Layout, dim: usize) -> Result<(usize, usize, usize)> {
    let left = product(&layout.dims()[..dim])?;
    let right = product(&layout.dims()[dim + 1..])?;
    Ok((left, layout.dims()[dim], right))
}

