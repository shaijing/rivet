pub(crate) fn cast(
    device: &CudaDevice,
    src: &CudaStorageSlice,
    layout: &Layout,
    dtype: DType,
) -> Result<CudaStorageSlice> {
    let view = layout_view(src, layout)?;
    macro_rules! cast_targets {
        ($src:expr, $src_ty:ty, $src_name:literal, $dtype:expr, $(($dst_variant:ident, $dst_ty:ty, $dst_name:literal)),+ $(,)?) => {
            match $dtype {
                $(
                    DType::$dst_variant => {
                        let mut dst = CudaStorageSlice::zeros(&device.cuda_stream(), $dtype, layout.checked_elem_count()?)?;
                        if let CudaStorageSlice::$dst_variant(output) = &mut dst {
                            launch_cast::<$src_ty, $dst_ty>(device, concat!("cast_", $src_name, "_", $dst_name), &$src, output, layout)?;
                            Ok(dst)
                        } else {
                            unreachable!()
                        }
                    }
                )+
                _ => Err(Error::UnsupportedDType { dtype: $dtype, op: "cuda_cast" }),
            }
        };
    }
    match view {
        CudaStorageView::U8(src) => cast_targets!(
            src,
            u8,
            "u8",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (I64, i64, "i64"),
            (BF16, half::bf16, "bf16"),
            (F16, half::f16, "f16"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        CudaStorageView::U32(src) => cast_targets!(
            src,
            u32,
            "u32",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (I64, i64, "i64"),
            (BF16, half::bf16, "bf16"),
            (F16, half::f16, "f16"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        CudaStorageView::I64(src) => cast_targets!(
            src,
            i64,
            "i64",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (I64, i64, "i64"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        CudaStorageView::BF16(src) => cast_targets!(
            src,
            half::bf16,
            "bf16",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (BF16, half::bf16, "bf16"),
            (F16, half::f16, "f16"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        CudaStorageView::F16(src) => cast_targets!(
            src,
            half::f16,
            "f16",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (BF16, half::bf16, "bf16"),
            (F16, half::f16, "f16"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        CudaStorageView::F32(src) => cast_targets!(
            src,
            f32,
            "f32",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (I64, i64, "i64"),
            (BF16, half::bf16, "bf16"),
            (F16, half::f16, "f16"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        CudaStorageView::F64(src) => cast_targets!(
            src,
            f64,
            "f64",
            dtype,
            (U8, u8, "u8"),
            (U32, u32, "u32"),
            (I64, i64, "i64"),
            (BF16, half::bf16, "bf16"),
            (F16, half::f16, "f16"),
            (F32, f32, "f32"),
            (F64, f64, "f64")
        ),
        _ => Err(Error::UnsupportedDType {
            dtype: src.dtype(),
            op: "cuda_cast",
        }),
    }
}

